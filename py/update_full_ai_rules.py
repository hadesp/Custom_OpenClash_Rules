#!/usr/bin/env python3
"""Validate and mirror Full AI domain providers; publish only a complete valid batch."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = 'https://raw.githubusercontent.com/MetaCubeX/meta-rules-dat/meta/geo/geosite/'
SOURCES = {
    'openai': ('rule/ChatGPT_Domain.yaml', 10, ['chatgpt.com', 'openai.com', 'oaistatic.com', 'oaiusercontent.com']),
    'google-gemini': ('rule/ai/google-gemini.yaml', 10, ['gemini.google.com', 'generativelanguage.googleapis.com', 'antigravity.google']),
    'anthropic': ('rule/ai/anthropic.yaml', 5, ['claude.ai', 'anthropic.com']),
    'bing': ('rule/ai/bing.yaml', 10, ['bing.com', 'copilot.microsoft.com']),
    'xai': ('rule/ai/xai.yaml', 3, ['grok.com', 'x.ai']),
    'category-ai-!cn': ('rule/ai/category-ai-!cn.yaml', 50, ['perplexity.ai', 'openrouter.ai']),
    'category-ai-cn': ('rule/ai/category-ai-cn.yaml', 30, ['deepseek.com', 'doubao.com']),
}
EXTRA_PATH = 'rule/Gemini_Extra_Domain.yaml'
OVERRIDES_PATH = 'rule/ai/overrides.json'
FORBIDDEN = {'com', 'net', 'org', 'google.com', 'googleapis.com', 'gstatic.com', 'cloudflare.com', 'githubusercontent.com'}

def domain(value: str) -> str:
    value = value.strip().lower()
    host = value[2:] if value.startswith('+.') else value
    # The upstream Bing list legitimately includes Microsoft's .bing brand TLD.
    if host in FORBIDDEN or len(host) > 253 or '.' not in host and value != '+.bing':
        raise ValueError(f'unsafe AI domain scope: {value}')
    if not all(re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', part) for part in host.split('.')):
        raise ValueError(f'invalid domain payload: {value}')
    return value

def parse_payload(content: str) -> list[str]:
    found = False
    values = []
    for raw in content.lstrip('\ufeff').splitlines():
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        if line == 'payload:' and not found:
            found = True
            continue
        if not found or not raw[:1].isspace() or not line.startswith('- '):
            raise ValueError('expected a YAML domain payload list')
        value = line[2:].strip()
        if value.startswith('"'):
            value = json.loads(value)
        elif value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("''", "'")
        values.append(domain(value))
    if not found or not values:
        raise ValueError('empty domain provider')
    return sorted(set(values))

def covers(values: list[str], host: str) -> bool:
    return any(value == host or value.startswith('+.') and (host == value[2:] or host.endswith('.' + value[2:])) for value in values)

def validate(values: list[str], minimum: int, required: list[str]) -> None:
    if not minimum <= len(values) <= 20_000:
        raise ValueError(f'unexpected domain count: {len(values)}')
    if not all(covers(values, host) for host in required):
        raise ValueError('upstream lost required service domains')

def download(name: str) -> str:
    request = urllib.request.Request(UPSTREAM + name + '.yaml', headers={'User-Agent': 'hadesp-Full-AI-rules-updater'})
    with urllib.request.urlopen(request, timeout=25) as response:
        content = response.read(5 * 1024 * 1024 + 1)
    if len(content) > 5 * 1024 * 1024:
        raise ValueError('oversized upstream provider')
    return content.decode('utf-8-sig')

def render(values: list[str], source: str) -> str:
    return ('# AUTO-GENERATED by py/update_full_ai_rules.py\n'
            f'# SOURCE: {source}\n'
            '# Local additions: rule/ai/overrides.json\n'
            'payload:\n' + ''.join('  - ' + value + '\n' for value in values))

def prepare(root: Path, fetch=download) -> dict[str, str]:
    overrides = json.loads((root / OVERRIDES_PATH).read_text(encoding='utf-8'))
    expected = {value[0] for value in SOURCES.values()} | {EXTRA_PATH}
    if not isinstance(overrides, dict) or set(overrides) - expected:
        raise ValueError('unknown override output path')
    extras = {}
    for key, values in overrides.items():
        if not isinstance(values, list) or not all(isinstance(value, str) for value in values):
            raise ValueError('override domains must be a string list')
        extras[key] = [domain(value) for value in values]
    outputs = {}
    for name, (output, minimum, required) in SOURCES.items():
        upstream = parse_payload(fetch(name))
        validate(upstream, minimum, required)
        old_file = root / output
        if old_file.exists() and len(upstream) < len(parse_payload(old_file.read_text(encoding='utf-8'))) * .7:
            raise ValueError(f'{name} lost more than 30% of its domains; refusing automatic publication')
        values = sorted(set(upstream) | set(extras.get(output, [])))
        validate(values, minimum, required)
        outputs[output] = render(values, UPSTREAM + name + '.yaml')
    supplemental = sorted(set(extras.get(EXTRA_PATH, [])))
    validate(supplemental, 4, ['antigravity.google.com', 'businessaicode.googleapis.com', 'aiplatform.googleapis.com'])
    outputs[EXTRA_PATH] = render(supplemental, 'https://antigravity.google/docs/enterprise')
    return outputs

def publish(root: Path, outputs: dict[str, str]) -> list[str]:
    # All downloads and validation finish before touching an output. GitHub only
    # commits after the entire batch and the Full regression checks succeed.
    changed = []
    for relative, content in outputs.items():
        output = root / relative
        if output.exists() and output.read_text(encoding='utf-8') == content:
            continue
        output.parent.mkdir(parents=True, exist_ok=True)
        descriptor, temporary = tempfile.mkstemp(prefix='.' + output.name + '.', dir=output.parent)
        try:
            with os.fdopen(descriptor, 'w', encoding='utf-8', newline='\n') as stream:
                stream.write(content)
            os.replace(temporary, output)
        finally:
            Path(temporary).unlink(missing_ok=True)
        changed.append(relative)
    return changed

def check(root: Path) -> None:
    for output, minimum, required in SOURCES.values():
        validate(parse_payload((root / output).read_text(encoding='utf-8')), minimum, required)
    validate(parse_payload((root / EXTRA_PATH).read_text(encoding='utf-8')), 4,
             ['antigravity.google.com', 'businessaicode.googleapis.com', 'aiplatform.googleapis.com'])

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='validate checked-in files without downloading')
    parser.add_argument('--source-dir', type=Path, help='use public YAML snapshots for an offline regression run')
    args = parser.parse_args()
    if args.check:
        check(ROOT)
        print('Validated all 8 mirrored AI providers.')
        return
    fetch = (lambda name: (args.source_dir / (name + '.yaml')).read_text(encoding='utf-8')) if args.source_dir else download
    outputs = prepare(ROOT, fetch)
    changed = publish(ROOT, outputs)
    print(f'Validated all 8 AI providers; {len(changed)} changed files.')
    for name in changed:
        print(name)

if __name__ == '__main__':
    main()
